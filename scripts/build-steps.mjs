#!/usr/bin/env node
// Builds the app's step data from the step files in content/steps/ (#44).
//
// Run it with `npm run build:steps`. It also runs automatically before
// `npm start`, `npm test` and `npm run build`, so editing and merging a step
// file updates the deployed app with no code change.
//
// It first runs the step content check (#45). If any step file is wrong it
// stops and writes nothing, so a broken step can never reach the app.
// Otherwise it writes src/core/steps.generated.ts: every step with its id,
// sorted by id, typed as Step so the TypeScript build checks it once more.

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkContent } from './check-content.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Checks the step files and writes the generated step data.
 *
 * @param {object} [options]
 * @param {string} [options.contentDir] Folder that holds step.schema.json and steps/.
 * @param {string} [options.outFile] Where to write the generated TypeScript file.
 * @param {Date} [options.today] Passed on to the content check.
 * @returns {{ ids: string[], errors: string[], warnings: string[] }}
 *   `ids` lists the steps written. When `errors` is not empty, nothing was written.
 */
export function buildSteps({
  contentDir = resolve(root, 'content'),
  outFile = resolve(root, 'src', 'core', 'steps.generated.ts'),
  today = new Date(),
} = {}) {
  const { steps, errors, warnings } = checkContent({ contentDir, today });
  if (errors.length > 0) {
    return { ids: [], errors, warnings };
  }

  const ids = Object.keys(steps).sort();
  const data = ids.map((id) => {
    const { $schema, ...fields } = steps[id];
    return { id, ...fields };
  });
  writeFileSync(outFile, renderModule(data));
  return { ids, errors, warnings };
}

/** The generated TypeScript module for the given steps. */
export function renderModule(data) {
  return [
    '// Generated by scripts/build-steps.mjs from content/steps/. Do not edit:',
    '// change the step files instead, and this file is rebuilt before start, test and build.',
    '',
    "import type { Step } from './step';",
    '',
    `export const stepData: readonly Step[] = ${JSON.stringify(data, null, 2)};`,
    '',
  ].join('\n');
}

// Run as a command: print the result and exit with 1 if anything is wrong.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { ids, errors, warnings } = buildSteps();
  for (const warning of warnings) console.warn(`Warning: ${warning}`);
  if (errors.length > 0) {
    console.error(`Step data not built, the content check found ${errors.length} problem(s):`);
    for (const error of errors) console.error(`  - ${error}`);
    process.exit(1);
  }
  console.log(`Step data built: ${ids.length} step(s) written to src/core/steps.generated.ts.`);
}
